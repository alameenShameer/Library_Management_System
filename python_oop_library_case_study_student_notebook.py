"""---
## Step 2 · `Member`, `Student` and `Teacher`
| Class / method | What it does |
|---|---|
| Member(member_id, name) | has an empty list `borrowed`; `max_books()` returns 1, `member_type()` returns `"Member"`; `can_borrow()` is `True` while the borrowed list is shorter than `max_books()`; `__str__()` returns `M1 | Anu | Student | Borrowed: 0/2` |
| Student(Member) | **inherits** from `Member`; overrides `max_books()` (2 books) and `member_type()` (`"Student"`) |
| Teacher(Member) | inherits from `Member`; overrides `max_books()` (4 books) and `member_type()` (`"Teacher"`) |

> Write `Member` first. `Student` and `Teacher` should be very short: they **inherit** everything and only **override** two methods.
"""

# Write the Member class here
class Member:
  def __init__(self,member_id,name):
    self.member_id=member_id
    self.name=name
    self.borrowed=[]

  def max_books(self):
    return 1

  def member_type(self):
    return "Member"

  def can_borrow(self):
    if len(self.borrowed) < self.max_books():
      return True
    return False

  def __str__(self):
    return f"{self.member_id} | {self.name} | {self.member_type()} | Borrowed:{len(self.borrowed)}/{self.max_books()}"

# Write the Student and Teacher classes here
class Student(Member):
  def __init__(self,member_id,name):
    super().__init__(member_id,name)

  def max_books(self):
    return 2

  def member_type(self):
    return "Student"

class Teacher(Member):
  def __init__(self,member_id,name):
    super().__init__(member_id,name)

  def max_books(self):
    return 4

  def member_type(self):
    return "Teacher"

