"""---
## Step 3 · The `Library` class
| Class / method | What it does |
|---|---|
| Library() | holds two dictionaries: `books` (id to `Book` object) and `members` (id to member object) |
| Library.load_books(data) / load_members(data) | create the objects from the starter data (a member of type `"teacher"` becomes a `Teacher`, otherwise a `Student`) |
| Library.issue_book(member_id, book_id) | returns a message: `Member not found`, `Book not found`, `Anu has reached the limit`, `Data Science 101 is not available` or, on success, `Anu issued Python Basics` (and records the id in the member's `borrowed` list) |
| Library.return_book(member_id, book_id) | returns `Anu returned Data Science 101` and gives the copy back; returns `Cannot return` if that member did not borrow that book |
| Library.show_books() / show_members() | print every book / member using `print(object)` |

> `issue_book` checks, in this order: member exists, book exists, member is under the limit, a copy is available.
"""

# Write the Library class here
class Library:
  def __init__(self):
    self.books={}
    self.members={}

  def load_books(self,data):
    for id,book in data.items():
      self.books[id]=Book(id,book["title"],book["author"],book["copies"])

  def load_members(self,datas):
    for data in datas:
      if data["type"]=="teacher":
        self.members[data["id"]]=Teacher(data["id"],data["name"])

      elif data["type"]=="student":
        self.members[data["id"]]=Student(data["id"],data["name"])

#returns a message: Member not found, Book not found, Anu has reached the limit, Data Science 101 is not available or, on success, Anu issued Python Basics (and records the id in the member's borrowed list)
  def issue_book(self,member_id,book_id):
    if member_id not in self.members:
      return f"Member not found"
    elif book_id not in self.books:
      return f"Book not found"
    elif not self.members[member_id].can_borrow():
      return f"{self.members[member_id].name} has reached the limit"
    elif not self.books[book_id].can_issue():
      return f"{self.books[book_id].title} is not available"
    else:
      self.members[member_id].borrowed.append(book_id)
      self.books[book_id].issue()
      return f"{self.members[member_id].name} issued {self.books[book_id].title}"

#Library.return_book(member_id, book_id)	returns Anu returned Data Science 101 and gives the copy back; returns Cannot return if that member did not borrow that book
  def return_book(self,member_id,book_id):
    if book_id in self.members[member_id].borrowed:
      self.members[member_id].borrowed.remove(book_id)
      self.books[book_id].give_back()
      return f"{self.members[member_id].name} returned {self.books[book_id].title}"
    else:
      return f"Cannot return"

  def show_books(self):
    for book in self.books.values():
      print(book)

  def show_members(self):
    for member in self.members.values():
      print(member)

