"""---
## Step 1 · The `Book` class
| Class / method | What it does |
|---|---|
| Book(book_id, title, author, copies) | stores the details; the number of copies is **private** (`self.__copies`) |
| Book.available_copies() | returns the number of copies left |
| Book.issue() | if a copy is left, reduce the copies by one and return `True`; otherwise return `False` |
| Book.give_back() | adds one copy back |
| Book.__str__() | returns `B101 | Python Basics by Anu | Copies: 2` |

> Use `self.__copies` (two underscores) so that the number of copies is **private**.
"""

# Write the Book class here
class Book:
  def __init__(self,book_id,title,author,copies):
    self.book_id=book_id
    self.title=title
    self.author=author
    self.__copies=copies

  def available_copies(self):
    return self.__copies

  def can_issue(self):
    if self.available_copies()>0:
      return True
    return False

  def issue(self):
    if self.available_copies()>0:
      self.__copies-=1
      return True
    return False

  def give_back(self):
    self.__copies+=1

  def __str__(self):
    return f"{self.book_id} | {self.title} by {self.author} | Copies: {self.__copies}"

